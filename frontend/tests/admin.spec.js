import { test, expect } from '@playwright/test';
import { manager } from './support.js';
test.beforeEach(async ({page}) => manager(page));

test('后台编辑产品与服务后可在官网看到更新，支持新增下架与删除', async ({ page }) => {
  await page.goto('/admin.html');
  await expect(page.getByRole('heading', { name: '网站概览' })).toBeVisible();
  await page.getByRole('link', { name: '产品管理', exact: true }).click();
  await page.getByRole('button', { name: '新增产品' }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('产品名称').fill('测试专用服务器');
  await dialog.getByLabel('产品简介').fill('业务测试整机');
  await dialog.getByRole('button', { name: '保存产品' }).click();
  await expect(page.getByRole('row').filter({ hasText: '测试专用服务器' })).toBeVisible();
  await page.goto('/#/products');
  await expect(page.getByRole('heading', { name: '测试专用服务器' })).toBeVisible();
  await page.goto('/admin.html#/products');
  const row = page.getByRole('row').filter({ hasText: '测试专用服务器' });
  await row.getByRole('button', { name: '下架' }).click();
  await page.goto('/#/products');
  await expect(page.getByRole('heading', { name: '测试专用服务器' })).toHaveCount(0);
  await page.goto('/admin.html#/services');
  await page.getByRole('row').filter({ hasText: '模型推理优化' }).getByRole('button', { name: '编辑' }).click();
  await page.getByLabel('服务名称').fill('模型推理优化测试');
  await page.getByRole('button', { name: '保存服务' }).click();
  await page.goto('/#/services');
  await expect(page.getByRole('heading', { name: '模型推理优化测试' })).toBeVisible();
  await page.goto('/admin.html#/services');
  await page.getByRole('row').filter({hasText:'模型推理优化测试'}).getByRole('button',{name:'编辑'}).click();
  await page.getByLabel('服务名称').fill('模型推理优化');
  await page.getByRole('button',{name:'保存服务'}).click();
});

test('后台可处理官网咨询并将设置同步到页脚，文本不作为HTML执行', async ({ page }) => {
  await page.goto('/admin.html');
  await page.goto('/#/partners');
  await page.getByRole('button',{name:'申请成为合作伙伴'}).click();
  await page.getByLabel('您的称呼').fill('端到端测试联系人');
  await page.getByLabel('联系电话').fill('13800138000');
  await page.getByLabel('公司名称').fill('端到端演示企业');
  await page.getByLabel('需求描述').fill('整机选型');
  await page.getByLabel('我同意将填写的信息用于本次业务联系').check();
  await page.getByRole('button',{name:'提交需求'}).click();
  await expect(page.getByRole('heading',{name:'需求已提交'})).toBeVisible();
  await page.goto('/admin.html');
  await page.getByRole('link', { name: '咨询记录', exact: true }).click();
  await page.getByRole('row').filter({hasText:'端到端测试联系人'}).getByRole('button', { name: '查看详情' }).click();
  await expect(page.getByRole('dialog').getByText('整机选型')).toBeVisible();
  await page.getByRole('button', { name: '标记已处理' }).click();
  await expect(page.getByRole('row').filter({hasText:'端到端测试联系人'}).getByText('已处理', { exact: true })).toBeVisible();
  await page.locator('summary').filter({hasText:'系统设置'}).click();
  await page.getByRole('link', { name: '联系方式', exact: true }).click();
  await page.getByLabel('联系邮箱').fill('demo@example.com');
  await page.getByLabel('联系地址').fill('<img src=x onerror=alert(1)>');
  await page.getByRole('button', { name: '保存设置' }).click();
  await expect(page.getByRole('status')).toContainText('联系信息已保存');
  await page.goto('/');
  await expect(page.getByText('demo@example.com')).toBeVisible();
  await expect(page.getByText('<img src=x onerror=alert(1)>')).toBeVisible();
  expect(await page.locator('img[src=x]').count()).toBe(0);
});
